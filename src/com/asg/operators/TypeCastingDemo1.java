package com.asg.operators;

public class TypeCastingDemo1 {

	public static void main(String[] args) {
		  
        int x = 'a';
         
        System.out.println(x);
        
        double d = 10;
        
        System.out.println(d);
        
        byte b = (byte)150;
        
        System.out.println(b);
        
        int a = (int)200.456;
        
        System.out.println(a);

	}

}
