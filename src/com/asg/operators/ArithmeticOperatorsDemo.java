package com.asg.operators;

public class ArithmeticOperatorsDemo {

	public static void main(String[] args) {
		    int a = 5;
		    int b = 10;
		    System.out.println(a+b);
		    
		    System.out.println(b-a);
		    
		    System.out.println(a*b);
		    
		    int x = 20;   
		    System.out.println(x/2);
		    
		    System.out.println(x%2);

	}

}
