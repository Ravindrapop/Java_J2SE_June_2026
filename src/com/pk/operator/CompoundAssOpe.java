package com.pk.operator;

public class CompoundAssOpe {
	
	public static void main (String[] args) {
		
		int a = 10;
		 a += 30;   //a = a + 30;
		 
		 System.out.println(a);  //a = 40
		 
		 a -= 20;  //a = a - 20;
		 System.out.println(a); //a = 20;
		 
		 a *= 5; //a = a*5;
		 System.out.println(a); // a = 100;
		 
		 a /= 5; //a = a/5;
		 System.out.println(a); // a = 20;
		 
		 a %= 3; // a = a % 3;
		 System.out.println(a); // a = 2;
		 
	}

}
